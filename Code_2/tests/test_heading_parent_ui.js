const app=fs.readFileSync(path.join(__dirname,'../functions/web/static/app.js'),'utf8');
const elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{value:'',checked:false,disabled:false,classList:{toggle(){}}});return elements.get(id);};
