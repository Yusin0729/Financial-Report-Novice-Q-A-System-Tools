let submitted;
const sandbox=vm.createContext({$,state,window:{},document:{querySelector:()=>({value:'retrieve'})},
  start:task=>{submitted=task;},alertMessage:message=>{throw Error(message);}});
vm.runInContext(app.split('\n').filter(line=>line.startsWith('function selectedQueryIndexes()')||line.startsWith('function updateMode()')||line.startsWith("$('query-form').onsubmit=")).join('\n'),sandbox);
vm.runInContext('updateMode()',sandbox);
assert.equal($('query-heading-parent').disabled,false);
